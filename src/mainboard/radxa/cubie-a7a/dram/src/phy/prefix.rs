//! DevInit CSR program before the DRAM reset is released (pstate 1), as
//! replayed from the reference oracle (PMU emulator trace of DevInit; see
//! `tools/native-dram-controls/tests/fixtures/devinit-prefix-pstate1.txt`).
//!
//! PROVISIONAL diagnostic table: impedance calibration (0x203xx), DLL lock
//! (0x20078/0x20200/0x200a2), ACSMCkeControl, PUBMODE, per-DBYTE receiver
//! calibration runs (0x1n057 enable, timed) and related setup, in the
//! firmware's order with its timed waits replaced by generous fixed waits.
//! The firmware's own evaluation of the DBYTE calibration (0x1n0ac pulses,
//! 0x1n0d0..d5 reads) is omitted; values it derived under the emulator's
//! synthetic inputs (0x1n0d9) are replayed as recorded. To be replaced by
//! understood, parameterized code group by group.

